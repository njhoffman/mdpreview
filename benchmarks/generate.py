#!/usr/bin/python3
"""Write the deterministic benchmark inputs (small, medium, large, code) next to this script."""

from pathlib import Path

HERE = Path(__file__).resolve().parent
LANGUAGES = [
  ("python", ['def greet(name):', '    """Say hello."""', '    return f"hello {name}"']),
  ("rust", ['fn main() {', '    let total: u32 = (1..=10).sum();', '    println!("{total}");', '}']),
  ("bash", ['for file in ./*.md; do', '  printf "%s\\n" "$file"', 'done']),
  ("go", ['func add(a, b int) int {', '\treturn a + b', '}']),
  ("javascript", ['const items = [1, 2, 3].map((x) => x * 2);', 'console.log(items);']),
  ("sql", ['SELECT name, count(*) FROM users', 'WHERE active GROUP BY name;']),
]


def section(index, table_rows):
  language, code = LANGUAGES[index % len(LANGUAGES)]
  lines = [
    f"## Section {index}",
    "",
    f"Paragraph {index} has **bold**, *italic*, `inline code`, a [link](https://example.com/{index}) and",
    "enough ordinary words to wrap at narrow widths so the renderer has some layout work to do here.",
    "",
    f"- Item one for section {index}",
    "  - Nested item with `code`",
    "  - [ ] Unchecked task",
    "  - [x] Checked task",
    "- Item two",
    "",
    "> A quoted line with *emphasis*.",
    "",
    f"```{language}",
    *code,
    "```",
    "",
  ]
  if table_rows:
    lines += ["| Name | Value | Notes |", "|---|---:|---|"]
    lines += [f"| `row{row}` | {row * index} | note {row} |" for row in range(1, table_rows + 1)]
    lines.append("")
  return lines


def document(title, sections, table_rows, table_every):
  lines = [f"# {title}", "", "Generated by benchmarks/generate.py; do not edit.", ""]
  for index in range(1, sections + 1):
    lines += section(index, table_rows if index % table_every == 0 else 0)
  return "\n".join(lines) + "\n"


def code_document(blocks):
  """Mostly fenced code blocks, cycling through the injected languages, to time code highlighting."""
  lines = ["# Benchmark code", "", "Generated by benchmarks/generate.py; do not edit.", ""]
  for index in range(1, blocks + 1):
    language, code = LANGUAGES[index % len(LANGUAGES)]
    lines += [f"Block {index} ({language}):", "", f"```{language}"]
    for repeat in range(3):
      lines += [line.replace("10", str(10 + repeat)) for line in code]
    lines += ["```", ""]
  return "\n".join(lines) + "\n"


SIZES = {
  "small": dict(sections=2, table_rows=5, table_every=2),
  "medium": dict(sections=15, table_rows=10, table_every=3),
  "large": dict(sections=40, table_rows=10, table_every=4),
}

if __name__ == "__main__":
  for name, spec in SIZES.items():
    (HERE / f"{name}.md").write_text(document(f"Benchmark {name}", **spec))
  (HERE / "code.md").write_text(code_document(blocks=40))
